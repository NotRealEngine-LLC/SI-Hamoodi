// Types used for AI integration

// Check if Puter.js is available
declare global {
  interface Window {
    puter?: {
      ai: {
        chat: (prompt: string | Array<{ role: string; content: string }>, options?: { model?: string; stream?: boolean }) => Promise<string | ReadableStream>;
      };
      auth: {
        isSignedIn: () => Promise<boolean>;
        signIn: () => Promise<void>;
        getUser: () => Promise<{ uuid: string; username: string } | null>;
      };
    };
  }
}

export function isPuterAvailable(): boolean {
  return typeof window !== 'undefined' && !!window.puter?.ai;
}

export async function isPuterSignedIn(): Promise<boolean> {
  if (!window.puter?.auth) return false;
  try {
    return await window.puter.auth.isSignedIn();
  } catch {
    return false;
  }
}

export interface AIRequestOptions {
  model?: string;
  conversationHistory?: Array<{ role: string; content: string }>;
  onStream?: (chunk: string) => void;
  signal?: AbortSignal;
}

export async function sendAIRequest(
  userMessage: string,
  options: AIRequestOptions = {}
): Promise<string> {
  if (!isPuterAvailable()) {
    // Simulated response when Puter is not available
    return generateSimulatedResponse(userMessage);
  }

  try {
    const messages = [
      ...(options.conversationHistory || []),
      { role: 'user', content: userMessage },
    ];

    const response = await window.puter!.ai.chat(messages, {
      model: options.model || 'gpt-4o-mini',
      stream: !!options.onStream,
    });

    if (typeof response === 'string') {
      return response;
    }

    // Handle streaming response
    if (response instanceof ReadableStream && options.onStream) {
      const reader = response.getReader();
      let fullText = '';
      
      while (true) {
        const { done, value } = await reader.read();
        if (done) break;
        const chunk = new TextDecoder().decode(value);
        fullText += chunk;
        options.onStream(chunk);
      }
      
      return fullText;
    }

    return String(response);
  } catch (error) {
    const errMsg = error instanceof Error ? error.message : 'Unknown AI error';
    throw new Error(`AI request failed: ${errMsg}`);
  }
}

